package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sync/atomic"
	"syscall"
	"time"
)

// partitionLifecycleLocksHeld counts partition lifecycle locks held in this process. B.2 uses it
// to enforce the single lock order `allocator (brief) → partition`: taking the allocator lock
// while a partition lock is held would be an inversion, and is recorded as a violation.
var partitionLifecycleLocksHeld atomic.Int64

func partitionLifecycleLockHeldNow() bool { return partitionLifecycleLocksHeld.Load() > 0 }

// partitionLifecycleLock prevents a local partition mutation from racing an
// exact-content proof generated by another VK process.
type partitionLifecycleLock struct {
	file    *os.File
	path    string
	ownerID uint64
}

func acquirePartitionLifecycleLock(storage string, deadlineIndex, partitionIndex int) (*partitionLifecycleLock, error) {
	dir := filepath.Join(storage, "partition-locks")
	if err := os.MkdirAll(dir, 0700); err != nil {
		return nil, fmt.Errorf("create partition lock directory: %w", err)
	}
	path := filepath.Join(dir, fmt.Sprintf("dl%d-pt%d.lock", deadlineIndex, partitionIndex))
	file, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return nil, fmt.Errorf("open partition lifecycle lock: %w", err)
	}
	// B.3: the permitted order is allocator → partition → coordination. Holding the innermost
	// coordination lock while taking a partition lock inverts it.
	notePartitionLockAcquiring()
	waitStarted := time.Now()
	if err := syscall.Flock(int(file.Fd()), syscall.LOCK_EX); err != nil {
		_ = file.Close()
		return nil, fmt.Errorf("acquire partition lifecycle lock: %w", err)
	}
	if waited := time.Since(waitStarted); waited >= 250*time.Millisecond {
		log.Printf("[partition-lock] dl=%d pt=%d waited=%s", deadlineIndex, partitionIndex, waited.Round(time.Millisecond))
	}
	partitionLifecycleLocksHeld.Add(1)
	ownerID := partitionLockOwners.acquired()
	return &partitionLifecycleLock{file: file, path: path, ownerID: ownerID}, nil
}

func (lock *partitionLifecycleLock) Release() {
	if lock == nil || lock.file == nil {
		return
	}
	if err := syscall.Flock(int(lock.file.Fd()), syscall.LOCK_UN); err != nil {
		log.Printf("[partition-lock] release warning path=%s: %v", lock.path, err)
	}
	if err := lock.file.Close(); err != nil {
		log.Printf("[partition-lock] close warning path=%s: %v", lock.path, err)
	}
	lock.file = nil
	partitionLockOwners.released(lock.ownerID)
	partitionLifecycleLocksHeld.Add(-1)
}
