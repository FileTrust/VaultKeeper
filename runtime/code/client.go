func newClientHost() host.Host {
	h, err := libp2p.New(libp2p.ListenAddrStrings("/ip4/0.0.0.0/tcp/0"))
	if err != nil {
		log.Fatal(err)
	}
	return h
}

// newClientHostWithIdentity gives capability-based multi-step client workflows a stable peer
// identity. Ordinary CLI calls stay ephemeral unless an explicit private-key path is supplied.
func newClientHostWithIdentity(keyPath string) host.Host {
	keyPath = strings.TrimSpace(keyPath)
	if keyPath == "" {
		return newClientHost()
	}
	privateKey, err := loadOrCreateClientIdentity(keyPath)
	if err != nil {
		log.Fatal(err)
	}
	h, err := libp2p.New(
		libp2p.ListenAddrStrings("/ip4/0.0.0.0/tcp/0"), libp2p.Identity(privateKey),
	)
	if err != nil {
		log.Fatal(err)
	}
	return h
}

func loadOrCreateClientIdentity(keyPath string) (libp2pcrypto.PrivKey, error) {
	if err := os.MkdirAll(filepath.Dir(keyPath), 0700); err != nil {
		return nil, fmt.Errorf("client identity directory: %w", err)
	}
	lock, err := os.OpenFile(keyPath+".lock", os.O_CREATE|os.O_RDWR, 0600)
	if err != nil {
		return nil, fmt.Errorf("client identity lock: %w", err)
	}
	defer lock.Close()
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_EX); err != nil {
		return nil, fmt.Errorf("client identity lock: %w", err)
	}
	defer syscall.Flock(int(lock.Fd()), syscall.LOCK_UN)

	var privateKey libp2pcrypto.PrivKey
	data, readErr := os.ReadFile(keyPath)
	if readErr == nil {
		info, statErr := os.Stat(keyPath)
		if statErr != nil || info.Mode().Perm() != 0600 {
			return nil, fmt.Errorf("client identity key must have mode 0600: %s", keyPath)
		}
		privateKey, err = libp2pcrypto.UnmarshalPrivateKey(data)
		if err != nil {
			return nil, fmt.Errorf("invalid client identity key %s: %w", keyPath, err)
		}
	} else if os.IsNotExist(readErr) {
		privateKey, _, err = libp2pcrypto.GenerateKeyPair(libp2pcrypto.Ed25519, -1)
		if err != nil {
			return nil, fmt.Errorf("generate client identity: %w", err)
		}
		data, err = libp2pcrypto.MarshalPrivateKey(privateKey)
		if err != nil {
			return nil, fmt.Errorf("marshal client identity: %w", err)
		}
		file, openErr := os.OpenFile(keyPath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
		if openErr != nil {
			return nil, fmt.Errorf("create client identity %s: %w", keyPath, openErr)
		}
		if _, err = file.Write(data); err == nil {
			err = file.Sync()
		}
		closeErr := file.Close()
		if err == nil {
			err = closeErr
		}
		if err != nil {
			return nil, fmt.Errorf("persist client identity %s: %w", keyPath, err)
		}
	} else {
		return nil, fmt.Errorf("read client identity %s: %w", keyPath, readErr)
	}
	return privateKey, nil
}

func tryOpenStream(ctx context.Context, h host.Host, addr string, protocols ...protocol.ID) (network.Stream, error) {
	maddr, err := ma.NewMultiaddr(addr)
	if err != nil {
		return nil, err
	}
	info, err := peer.AddrInfoFromP2pAddr(maddr)
	if err != nil {
		return nil, err
	}
	connectCtx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	if err := h.Connect(connectCtx, *info); err != nil {
		return nil, err
	}
	s, err := h.NewStream(connectCtx, info.ID, protocols...)
	if err != nil {
		return nil, err
	}
	return s, nil
}

func openStream(ctx context.Context, h host.Host, addr string, proto protocol.ID) network.Stream {
	s, err := tryOpenStream(ctx, h, addr, proto)
	if err != nil {
		log.Fatal(err)
	}
	return s
}

type transferProgressReader struct {
	r           io.Reader
	direction   string
	transferred int64
	total       int64
	lastReport  time.Time
}

func (p *transferProgressReader) Read(buf []byte) (int, error) {
	n, err := p.r.Read(buf)
	p.transferred += int64(n)
	now := time.Now()
	if n > 0 && (p.transferred >= p.total || now.Sub(p.lastReport) >= time.Second) {
		payload, _ := json.Marshal(map[string]any{
			"direction": p.direction, "bytes": p.transferred, "totalBytes": p.total,
		})
		fmt.Fprintf(os.Stderr, "FILETRUST_PROGRESS %s\n", payload)
		p.lastReport = now
	}
	return n, err
}

// runStore sends a piece to a remote VK server via the store protocol.
// commitmentNonce is a 0x-prefixed 32-byte hex value generated by DO; when
// non-empty it is forwarded in the StoreReq so the VK can compute
// commitmentHash = keccak256(pieceRoot || commitmentNonce) and register it on
// FileRegistrationSC. If empty, the VK generates its own nonce.
func runStore(ctx context.Context, peerAddr, filePath, fileID string, pieceIndex int, serviceEnd int64, commitmentNonce, paymentCommitment, fileFormat, deletionAuthHash, transferID, uploader string, transferIssuedAt int64, transferSig, expectedPieceRoot string, expectedPieceBlockSize int64) {
	f, err := os.Open(filePath)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	st, err := f.Stat()
	if err != nil {
		log.Fatal(err)
	}

	baseReq := StoreReq{
		FileID:                 fileID,
		Name:                   filepath.Base(filePath),
		PieceIndex:             pieceIndex,
		Size:                   st.Size(),
		Resume:                 true,
		ServiceEnd:             serviceEnd,
		CommitmentNonce:        commitmentNonce,
		PaymentCommitment:      paymentCommitment,
		FileFormat:             fileFormat,
		DeletionAuthHash:       deletionAuthHash,
		TransferID:             transferID,
		Uploader:               uploader,
		TransferIssuedAt:       transferIssuedAt,
		TransferSignature:      transferSig,
		ExpectedPieceRoot:      expectedPieceRoot,
		ExpectedPieceBlockSize: expectedPieceBlockSize,
	}

	h := newClientHost()
	defer h.Close()
	if validTransferID(transferID) && uploader != "" && transferSig != "" {
		// Negotiate V3 first. Closing a negotiated V2 stream without sending a
		// request lets rolling deployments fall back to the legacy probe flow.
		s, openErr := tryOpenStream(ctx, h, peerAddr, StoreProtocolV3, StoreProtocol)
		if openErr != nil {
			log.Fatal(openErr)
		}
		selected := s.Protocol()
		_ = s.Close()
		if selected == StoreProtocolV3 {
			runStoreV3(ctx, h, peerAddr, f, st.Size(), baseReq)
			return
		}
		log.Printf("[store] VK uses legacy store protocol; durable transfer admission is unavailable")
	}
	runStoreV2(ctx, h, peerAddr, f, st.Size(), baseReq)
}

func runStoreV3(ctx context.Context, h host.Host, peerAddr string, f *os.File, size int64, baseReq StoreReq) {
	for attempt := 1; attempt <= 100; attempt++ {
		s, err := tryOpenStream(ctx, h, peerAddr, StoreProtocolV3)
		if err != nil {
			log.Printf("[store resume] connect failed: %v", err)
			time.Sleep(time.Second)
			continue
		}
		writeJSON(s, baseReq)
		r := bufio.NewReader(s)
		var ready StoreResp
		if err := json.NewDecoder(r).Decode(&ready); err != nil {
			_ = s.Close()
			log.Printf("[store resume] admission response failed: %v", err)
			time.Sleep(time.Second)
			continue
		}
		if ready.Complete && ready.OK {
			_ = s.Close()
			writePrettyJSON(os.Stdout, ready)
			return
		}
		if ready.Busy {
			_ = s.Close()
			delay := ready.RetryAfterSeconds
			if delay <= 0 {
				delay = DefaultTransferRetryAfterSeconds
			}
			log.Printf("[store busy] %s; retrying in %ds", ready.Err, delay)
			time.Sleep(time.Duration(delay) * time.Second)
			continue
		}
		if !ready.OK || !ready.Ready {
			_ = s.Close()
			log.Fatal(ready.Err)
		}
		offset := ready.ResumeOffset
		if offset < 0 || offset > size {
			_ = s.Close()
			log.Fatalf("bad resume offset %d for size %d", offset, size)
		}
		if _, err := f.Seek(offset, io.SeekStart); err != nil {
			_ = s.Close()
			log.Fatal(err)
		}
		progress := &transferProgressReader{
			r: f, direction: "upload", transferred: offset, total: size,
		}
		if _, err := io.CopyN(s, progress, size-offset); err != nil {
			_ = s.Close()
			log.Printf("[store resume] transfer interrupted after byte %d: %v", progress.transferred, err)
			continue
		}
		var resp StoreResp
		if err := json.NewDecoder(r).Decode(&resp); err != nil {
			_ = s.Close()
			log.Printf("[store resume] final response failed: %v", err)
			continue
		}
		_ = s.Close()
		if resp.OK && resp.Complete {
			writePrettyJSON(os.Stdout, resp)
			return
		}
		if resp.ResumeOffset > offset {
			log.Printf("[store resume] %s; continuing at byte %d", resp.Err, resp.ResumeOffset)
			continue
		}
		log.Fatal(resp.Err)
	}
	log.Fatal("store resume attempts exhausted")
}

func runStoreV2(ctx context.Context, h host.Host, peerAddr string, f *os.File, size int64, baseReq StoreReq) {
	for attempt := 1; attempt <= 20; attempt++ {
		probeReq := baseReq
		probeReq.Probe = true
		ps := openStream(ctx, h, peerAddr, StoreProtocol)
		writeJSON(ps, probeReq)
		var probe StoreResp
		if err := json.NewDecoder(ps).Decode(&probe); err != nil {
			ps.Close()
			log.Fatal(err)
		}
		ps.Close()
		if !probe.OK {
			log.Fatal(probe.Err)
		}
		if probe.Complete {
			writePrettyJSON(os.Stdout, probe)
			return
		}
		offset := probe.ResumeOffset
		if offset < 0 || offset > size {
			log.Fatalf("bad resume offset %d for size %d", offset, size)
		}
		if _, err := f.Seek(offset, io.SeekStart); err != nil {
			log.Fatal(err)
		}

		req := baseReq
		req.Offset = offset
		s := openStream(ctx, h, peerAddr, StoreProtocol)
		writeJSON(s, req)
		progress := &transferProgressReader{r: f, direction: "upload", transferred: offset, total: size}
		if _, err := io.CopyN(s, progress, size-offset); err != nil {
			s.Close()
			log.Printf("[store resume] transfer interrupted at offset=%d: %v", offset, err)
			continue
		}
		var resp StoreResp
		if err := json.NewDecoder(s).Decode(&resp); err != nil {
			s.Close()
			log.Printf("[store resume] response read failed at offset=%d: %v", offset, err)
			continue
		}
		s.Close()
		if resp.OK {
			writePrettyJSON(os.Stdout, resp)
			return
		}
		if resp.ResumeOffset > offset {
			log.Printf("[store resume] %s; continuing at byte %d", resp.Err, resp.ResumeOffset)
			continue
		}
		log.Fatal(resp.Err)
	}
	log.Fatal("store resume attempts exhausted")
}

// runQuote opens a QuoteProtocol stream to VK, sends a QuoteReq, and prints the
// QuoteResp as JSON to stdout. DO calls this before depositing escrow so VK can
// generate and save all commitment secrets first.
//
// fileID, uploader, issuedAt and quoteSig are the data owner's signed proof that
// the quote is for a real file it owns (see vaultmeshQuoteAuthMessage). The
// signature binds the transferId, so a signed request must name one.
func runQuote(
	ctx context.Context, peerAddr string, size, serviceEnd int64, transferID,
	blockedDemandID, blockedDemandCapability, clientIdentityKey,
	fileID, uploader string, issuedAt int64, quoteSig string,
) {
	if quoteSig != "" && transferID == "" {
		log.Fatal("a signed quote request needs --transfer-id: the signature covers it")
	}
	h := newClientHostWithIdentity(clientIdentityKey)
	defer h.Close()
	if transferID == "" {
		nonce, err := randomNonce()
		if err != nil {
			log.Fatal(err)
		}
		transferID = "ftq_" + strings.TrimPrefix(nonce, "0x")
	}
	for attempt := 1; attempt <= 100; attempt++ {
		s, err := tryOpenStream(ctx, h, peerAddr, QuoteProtocol)
		if err != nil {
			log.Printf("[quote retry] connect failed: %v", err)
			time.Sleep(time.Second)
			continue
		}
		writeJSON(s, QuoteReq{
			Size: size, ServiceEnd: serviceEnd, TransferID: transferID,
			BlockedDemandID:         blockedDemandID,
			BlockedDemandCapability: blockedDemandCapability,
			FileID:                  fileID,
			Uploader:                uploader,
			IssuedAt:                issuedAt,
			Signature:               quoteSig,
		})
		var resp QuoteResp
		if err := json.NewDecoder(s).Decode(&resp); err != nil {
			_ = s.Close()
			log.Printf("[quote retry] response failed: %v", err)
			continue
		}
		_ = s.Close()
		if resp.Busy {
			// A capability-gated blocked-demand retry is also a private lifecycle poll. Return
			// its current state to the caller; the caller controls the longer proof wait.
			if blockedDemandID != "" {
				writePrettyJSON(os.Stdout, resp)
				return
			}
			delay := resp.RetryAfterSeconds
			if delay <= 0 {
				delay = DefaultTransferRetryAfterSeconds
			}
			log.Printf("[quote busy] %s; retrying in %ds", resp.Err, delay)
			time.Sleep(time.Duration(delay) * time.Second)
			continue
		}
		writePrettyJSON(os.Stdout, resp)
		return
	}
	log.Fatal("quote admission attempts exhausted")
}

