func runDelete(ctx context.Context, peerAddr, commitmentHash, deletionAuthSecret string, redriveCapable bool,
	requester string, issuedAt int64, signature string) {
	h := newClientHost()
	defer h.Close()
	for attempt := 1; attempt <= 100; attempt++ {
		s, err := tryOpenStream(ctx, h, peerAddr, DeleteProtocol)
		if err != nil {
			log.Printf("[delete retry] connect failed: %v", err)
			time.Sleep(time.Second)
			continue
		}
		writeJSON(s, DeleteReq{
			CommitmentHash:     commitmentHash,
			DeletionAuthSecret: deletionAuthSecret,
			RedriveCapable:     redriveCapable,
			Requester:          requester,
			IssuedAt:           issuedAt,
			Signature:          signature,
		})
		var resp DeleteResp
		if err := json.NewDecoder(bufio.NewReader(s)).Decode(&resp); err != nil {
			_ = s.Close()
			// The request may already have been durably declared. Never resend an
			// ambiguous deletion blindly; return control to the DO so it can check
			// the authoritative chain state using the stable commitment identity.
			writePrettyJSON(os.Stdout, DeleteResp{
				Pending: true, Phase: "response_unknown",
				DeletionID: strings.ToLower(strings.TrimSpace(commitmentHash)),
				Error:      "deletion response interrupted; reconcile on-chain before retry: " + err.Error(),
			})
			return
		}
		_ = s.Close()
		if resp.Busy {
			delay := resp.RetryAfterSeconds
			if delay <= 0 {
				delay = DefaultTransferRetryAfterSeconds
			}
			log.Printf("[delete busy] %s; retrying in %ds", resp.Error, delay)
			time.Sleep(time.Duration(delay) * time.Second)
			continue
		}
		writePrettyJSON(os.Stdout, resp)
		if !resp.OK {
			os.Exit(1)
		}
		return
	}
	log.Fatal("delete admission attempts exhausted")
}

