func runGet(ctx context.Context, peerAddr, pieceRoot, outPath, fileID, requester, sig string, issuedAt int64) {
	h := newClientHost()
	defer h.Close()
	if _, err := os.Stat(outPath); err == nil {
		got, _, _, _, err := computePieceCommitment(outPath, DefaultPieceBlockSize)
		if err == nil && sameRoot(got, pieceRoot) {
			fmt.Println("already downloaded and verified:", outPath)
			return
		}
	}
	partPath := outPath + ".part"
	for attempt := 1; attempt <= 100; attempt++ {
		offset := fileSizeIfExists(partPath)
		s, err := tryOpenStream(ctx, h, peerAddr, GetProtocol)
		if err != nil {
			log.Printf("[get resume] connect failed: %v", err)
			time.Sleep(time.Second)
			continue
		}
		writeJSON(s, GetReq{PieceRoot: pieceRoot, PieceID: pieceRoot, Offset: offset, FileID: fileID, Requester: requester, Signature: sig, IssuedAt: issuedAt})
		r := bufio.NewReader(s)
		var resp GetResp
		if err := json.NewDecoder(r).Decode(&resp); err != nil {
			_ = s.Close()
			log.Printf("[get resume] response failed: %v", err)
			continue
		}
		if resp.Busy {
			_ = s.Close()
			delay := resp.RetryAfterSeconds
			if delay <= 0 {
				delay = DefaultTransferRetryAfterSeconds
			}
			log.Printf("[get busy] %s; retrying in %ds", resp.Err, delay)
			time.Sleep(time.Duration(delay) * time.Second)
			continue
		}
		if !resp.OK {
			_ = s.Close()
			log.Fatal(resp.Err)
		}
		if resp.Offset != offset {
			_ = s.Close()
			log.Fatalf("resume offset mismatch: local=%d vk=%d", offset, resp.Offset)
		}
		out, err := os.OpenFile(partPath, os.O_CREATE|os.O_WRONLY, 0600)
		if err != nil {
			_ = s.Close()
			log.Fatal(err)
		}
		if _, err := out.Seek(offset, io.SeekStart); err != nil {
			out.Close()
			_ = s.Close()
			log.Fatal(err)
		}
		progress := &transferProgressReader{
			r: r, direction: "download", transferred: offset, total: resp.TotalSize,
		}
		_, copyErr := io.CopyN(out, progress, resp.Size)
		syncErr := out.Sync()
		closeErr := out.Close()
		_ = s.Close()
		if copyErr != nil || syncErr != nil || closeErr != nil {
			log.Printf("[get resume] interrupted after byte %d: copy=%v sync=%v close=%v", progress.transferred, copyErr, syncErr, closeErr)
			continue
		}
		blockSize := resp.PieceBlockSize
		if blockSize <= 0 {
			blockSize = DefaultPieceBlockSize
		}
		got, _, _, _, err := computePieceCommitment(partPath, blockSize)
		if err != nil {
			log.Fatal(err)
		}
		if !sameRoot(got, pieceRoot) {
			log.Fatalf("integrity failed, got %s", got)
		}
		if err := os.Rename(partPath, outPath); err != nil {
			log.Fatal(err)
		}
		fmt.Println("downloaded and verified:", outPath)
		return
	}
	log.Fatal("download resume attempts exhausted")
}

